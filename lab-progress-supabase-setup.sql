-- ---------------------------------------------------------------------------
-- 1. Course roster and activated user profiles
-- ---------------------------------------------------------------------------
create table if not exists public.course_roster (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(email)),
  roll_number text unique,
  full_name text not null,
  role text not null default 'student' check (role in ('student', 'instructor')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (role = 'instructor' or roll_number is not null)
);

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  roster_id bigint not null unique references public.course_roster(id) on delete cascade,
  email text not null unique,
  roll_number text,
  full_name text not null,
  role text not null check (role in ('student', 'instructor')),
  activated_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2. Lab tasks, student completion state, and audit history
-- ---------------------------------------------------------------------------
create table if not exists public.lab_tasks (
  task_id text primary key,
  lab_id text not null,
  task_order integer not null check (task_order > 0),
  title text not null,
  unique (lab_id, task_order)
);

